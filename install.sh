#!/usr/bin/env bash
# TimeFence installer (systemd, venv based). Idempotent: safe to re-run.
#
#   sudo ./install.sh
#   sudo BASE_PATH=/timer TZ=Asia/Kolkata ./install.sh
#   sudo ADGUARD_PASSWORD_FILE=/etc/timefence/adguard.pass ./install.sh --no-start
#
# Environment (all optional):
#   SERVICE_USER   default timefence      INSTALL_DIR  default /opt/timefence
#   DATA_DIR       default /var/lib/timefence
#   CONF_DIR       default /etc/timefence
#   BASE_PATH      default /              LISTEN_HOST  default 127.0.0.1
#   LISTEN_PORT    default 8099           TZ           default UTC
#   ADGUARD_URL    default http://127.0.0.1:3000
#   ADGUARD_USER   default admin
#   ADGUARD_PASSWORD_FILE  file the service user can read (recommended)
#   RECONCILE_INTERVAL default 30         TRUSTED_PROXIES default empty
#   SECURE_COOKIES default true           LOG_LEVEL    default INFO
set -euo pipefail

SERVICE_USER="${SERVICE_USER:-timefence}"
INSTALL_DIR="${INSTALL_DIR:-/opt/timefence}"
DATA_DIR="${DATA_DIR:-/var/lib/timefence}"
CONF_DIR="${CONF_DIR:-/etc/timefence}"
BASE_PATH="${BASE_PATH:-/}"
LISTEN_HOST="${LISTEN_HOST:-127.0.0.1}"
LISTEN_PORT="${LISTEN_PORT:-8099}"
TZ_VALUE="${TZ:-UTC}"
ADGUARD_URL="${ADGUARD_URL:-http://127.0.0.1:3000}"
ADGUARD_USER="${ADGUARD_USER:-admin}"
ADGUARD_PASSWORD="${ADGUARD_PASSWORD:-}"
ADGUARD_PASSWORD_FILE="${ADGUARD_PASSWORD_FILE:-}"
RECONCILE_INTERVAL="${RECONCILE_INTERVAL:-30}"
TRUSTED_PROXIES="${TRUSTED_PROXIES:-}"
SECURE_COOKIES="${SECURE_COOKIES:-true}"
LOG_LEVEL="${LOG_LEVEL:-INFO}"
START=1
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

for arg in "$@"; do
  case "$arg" in
    --no-start) START=0 ;;
    --help|-h) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

if [[ "${EUID}" -ne 0 ]]; then
  echo "run as root (sudo $0)" >&2
  exit 1
fi

say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

# --- 1. user --------------------------------------------------------------
if ! id -u "${SERVICE_USER}" >/dev/null 2>&1; then
  say "creating system user ${SERVICE_USER}"
  useradd --system --home-dir "${INSTALL_DIR}" --shell /usr/sbin/nologin \
          --comment "TimeFence for AdGuard Home" "${SERVICE_USER}"
else
  say "system user ${SERVICE_USER} already exists"
fi

# --- 2. directories -------------------------------------------------------
say "creating directories"
install -d -o root -g "${SERVICE_USER}" -m 750 "${INSTALL_DIR}"
install -d -o root -g "${SERVICE_USER}" -m 750 "${CONF_DIR}"
install -d -o "${SERVICE_USER}" -g "${SERVICE_USER}" -m 700 "${DATA_DIR}"

# --- 3. virtualenv + package ---------------------------------------------
if [[ ! -x "${INSTALL_DIR}/venv/bin/python" ]]; then
  say "creating virtualenv"
  python3 -m venv "${INSTALL_DIR}/venv"
fi
say "installing/upgrading TimeFence (this may take a minute)"
"${INSTALL_DIR}/venv/bin/pip" install --quiet --upgrade pip
"${INSTALL_DIR}/venv/bin/pip" install --quiet --upgrade "${SRC_DIR}"
"${INSTALL_DIR}/venv/bin/pip" install --quiet --upgrade "uvicorn[standard]==0.34.0"

# --- 4. configuration -----------------------------------------------------
ENV_FILE="${CONF_DIR}/timefence.env"
if [[ -f "${ENV_FILE}" ]]; then
  say "keeping existing ${ENV_FILE}"
else
  say "writing ${ENV_FILE}"
  umask 077
  cat >"${ENV_FILE}" <<ENV
# TimeFence configuration (generated by install.sh)
ADGUARD_URL=${ADGUARD_URL}
ADGUARD_USER=${ADGUARD_USER}
ADGUARD_PASSWORD=${ADGUARD_PASSWORD}
ADGUARD_PASSWORD_FILE=${ADGUARD_PASSWORD_FILE}
BASE_PATH=${BASE_PATH}
TZ=${TZ_VALUE}
LISTEN_HOST=${LISTEN_HOST}
LISTEN_PORT=${LISTEN_PORT}
DATA_DIR=${DATA_DIR}
RECONCILE_INTERVAL=${RECONCILE_INTERVAL}
TRUSTED_PROXIES=${TRUSTED_PROXIES}
SECURE_COOKIES=${SECURE_COOKIES}
LOG_LEVEL=${LOG_LEVEL}
ENV
  chown root:root "${ENV_FILE}"
  chmod 600 "${ENV_FILE}"
fi

if [[ -n "${ADGUARD_PASSWORD_FILE}" ]]; then
  if [[ ! -r "${ADGUARD_PASSWORD_FILE}" ]]; then
    echo "WARNING: ${ADGUARD_PASSWORD_FILE} is not readable by root; check it exists" >&2
  else
    # the service user must be able to read the password file
    chgrp "${SERVICE_USER}" "${ADGUARD_PASSWORD_FILE}" 2>/dev/null || true
    chmod 640 "${ADGUARD_PASSWORD_FILE}" 2>/dev/null || true
  fi
fi

# validate configuration with the app's own checks
say "validating configuration"
set -a; . "${ENV_FILE}"; set +a
if ! sudo -u "${SERVICE_USER}" env DATA_DIR="${DATA_DIR}" ADGUARD_PASSWORD="${ADGUARD_PASSWORD:-x}" \
      ADGUARD_PASSWORD_FILE="${ADGUARD_PASSWORD_FILE:-}" ADGUARD_URL="${ADGUARD_URL}" \
      ADGUARD_USER="${ADGUARD_USER}" BASE_PATH="${BASE_PATH}" TZ="${TZ_VALUE}" \
      LISTEN_PORT="${LISTEN_PORT}" RECONCILE_INTERVAL="${RECONCILE_INTERVAL}" \
      "${INSTALL_DIR}/venv/bin/python" -c 'import timefence.config as c; s=c.Settings.from_env(); s.validate(); print("configuration OK")'; then
  echo "configuration validation failed" >&2
  exit 1
fi

# --- 5. systemd ------------------------------------------------------------
say "installing systemd unit"
install -m 644 "${SRC_DIR}/deploy/timefence.service" /etc/systemd/system/timefence.service
systemctl daemon-reload

if [[ "${START}" -eq 1 ]]; then
  systemctl enable timefence.service >/dev/null
  systemctl restart timefence.service
  say "waiting for the service"
  for _ in $(seq 1 30); do
    if systemctl is-active --quiet timefence.service; then
      if curl -fsS -m 2 "http://${LISTEN_HOST}:${LISTEN_PORT}/healthz" >/dev/null 2>&1 \
         || curl -fsS -m 2 "http://${LISTEN_HOST}:${LISTEN_PORT}/timer/healthz" >/dev/null 2>&1; then
        break
      fi
    fi
    sleep 1
  done
  systemctl --no-pager --lines=5 status timefence.service || true
  say "TimeFence is running on http://${LISTEN_HOST}:${LISTEN_PORT}${BASE_PATH%/}/"
else
  say "skipping start (--no-start)"
fi

cat <<EOF

Done.

  configuration : ${ENV_FILE}  (600, root)
  data / SQLite : ${DATA_DIR}/timefence.db
  service       : timefence.service
  logs          : journalctl -u timefence -f

First login: admin / admin  (you will be forced to choose a new password and PIN)
EOF
