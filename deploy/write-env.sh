#!/usr/bin/env bash
# Shared by install.sh: write the service's environment file.
#
# Sourced, never run. Every value is single-quoted, so the app's own KEY=VALUE
# reader (timefence.__main__._read_env_file) gets it back byte for byte and the
# file is never evaluated by a shell. TZ is written only when the caller
# exported it; otherwise the app detects the host's timezone at start-up.

# Print one value as a single-quoted shell word. Inside the quotes a backslash
# escapes the next character, so a backslash and a single quote are doubled and
# prefixed; that is the only escape the app's reader undoes.
tf_quote() {
    local value
    value=$(printf '%s' "${1-}" | sed -e 's/\\/\\\\/g' -e "s/'/\\\\'/g")
    printf "'%s'" "$value"
}

tf_write_env_file() {
    local dest=$1 previous_umask
    previous_umask=$(umask)
    umask 077
    {
        printf '# TimeFence configuration (generated by install.sh)\n'
        printf 'ADGUARD_URL=%s\n' "$(tf_quote "${ADGUARD_URL-}")"
        printf 'ADGUARD_USER=%s\n' "$(tf_quote "${ADGUARD_USER-}")"
        printf 'ADGUARD_PASSWORD=%s\n' "$(tf_quote "${ADGUARD_PASSWORD-}")"
        printf 'ADGUARD_PASSWORD_FILE=%s\n' "$(tf_quote "${ADGUARD_PASSWORD_FILE-}")"
        printf 'BASE_PATH=%s\n' "$(tf_quote "${BASE_PATH-}")"
        if [ -n "${TZ-}" ]; then
            printf 'TZ=%s\n' "$(tf_quote "${TZ}")"
        else
            printf '# TZ=\n'
        fi
        printf 'LISTEN_HOST=%s\n' "$(tf_quote "${LISTEN_HOST-}")"
        printf 'LISTEN_PORT=%s\n' "$(tf_quote "${LISTEN_PORT-}")"
        printf 'DATA_DIR=%s\n' "$(tf_quote "${DATA_DIR-}")"
        printf 'RECONCILE_INTERVAL=%s\n' "$(tf_quote "${RECONCILE_INTERVAL-}")"
        printf 'TRUSTED_PROXIES=%s\n' "$(tf_quote "${TRUSTED_PROXIES-}")"
        printf 'SECURE_COOKIES=%s\n' "$(tf_quote "${SECURE_COOKIES-}")"
        printf 'LOG_LEVEL=%s\n' "$(tf_quote "${LOG_LEVEL-}")"
    } >"$dest"
    umask "$previous_umask"
}
